import { z } from "zod";

import {
  getProvider,
  enforceRateLimit,
  describeError,
  PlannerUnavailableError,
} from "@/lib/ai";
import { conciergeTools } from "@/lib/concierge/tools";
import { getDestinations, getTrips } from "@/lib/cms/catalogue";
import { recordInterest } from "@/lib/crm/interests";
import { CONCIERGE_SYSTEM, pageContextNote } from "@/lib/concierge/prompt";

export const dynamic = "force-dynamic";
export const maxDuration = 120;

const TURNS_PER_HOUR = 60;

// Conversation is held by the browser and replayed each turn — the server is
// stateless, which is what lets the concierge follow you across page loads
// without a session store.
const BodySchema = z.object({
  messages: z
    .array(
      z.object({
        role: z.enum(["user", "assistant"]),
        // Empty content is accepted here and dropped by normaliseTurns below,
        // rather than rejected. See the note there.
        content: z.string().max(4000),
      })
    )
    .min(1)
    .max(40),
  // Groups a conversation into ONE interest record instead of one per turn.
  // Generated by the browser; opaque to us and never used to identify a person.
  conversationId: z.string().max(64).optional(),
  context: z
    .object({
      page: z.string().max(120).optional(),
      title: z.string().max(200).optional(),
      tripSlug: z.string().max(120).optional(),
    })
    .optional(),
});

/**
 * Make a replayed conversation safe to send on.
 *
 * A stream that fails before producing any text — a quota refusal, a dropped
 * connection — leaves an empty assistant turn in the conversation the browser
 * saves. Replaying that turn used to fail schema validation, so every later
 * message in that conversation came back as "That didn't look right." The
 * visitor had done nothing wrong and the only way out was the Clear button,
 * which throws the whole conversation away.
 *
 * The client no longer keeps those turns, but this runs on the server because
 * conversations already saved in someone's browser have to heal themselves.
 *
 * Empty turns are dropped, consecutive same-role turns merged (the API expects
 * them to alternate) and any leading assistant turn removed.
 */
function normaliseTurns(messages) {
  const out = [];
  for (const message of messages) {
    const content = message.content.trim();
    if (!content) continue;
    const last = out[out.length - 1];
    if (last?.role === message.role) last.content = `${last.content}\n\n${content}`;
    else out.push({ role: message.role, content });
  }
  while (out.length > 0 && out[0].role === "assistant") out.shift();
  return out;
}

function sse(event, data) {
  return `event: ${event}\ndata: ${JSON.stringify(data)}\n\n`;
}

/**
 * Cards are the generative-UI half of this: a tool returns `_cards`, and the
 * browser renders them as real trip cards, comparisons and CTAs inside the
 * conversation. They are stripped before the result goes back to the model,
 * which only needs the data.
 */
function splitCards(result) {
  if (!result || typeof result !== "object" || !Array.isArray(result._cards)) {
    return { cards: [], forModel: result };
  }
  const { _cards, ...forModel } = result;
  return { cards: _cards, forModel };
}

export async function POST(request) {
  let body;

  try {
    enforceRateLimit(request, "concierge", TURNS_PER_HOUR);

    const parsed = BodySchema.safeParse(await request.json());
    if (!parsed.success) {
      return Response.json({ message: "That didn't look right." }, { status: 400 });
    }
    body = { ...parsed.data, messages: normaliseTurns(parsed.data.messages) };

    if (body.messages.length === 0) {
      return Response.json({ message: "Tell me what you're looking for." }, { status: 400 });
    }

    if (!getProvider()) throw new PlannerUnavailableError();
  } catch (error) {
    const { status, message } = describeError(error);
    return Response.json({ message }, { status });
  }

  const provider = getProvider();
  const encoder = new TextEncoder();

  const stream = new ReadableStream({
    async start(controller) {
      const send = (event, data) => controller.enqueue(encoder.encode(sse(event, data)));
      let pendingCards = [];
      // Falls back to a per-request id: worse grouping, never a lost signal.
      const conversationId = body.conversationId || `anon-${Date.now()}`;

      // The live catalogue, once per conversation turn, so the concierge
      // knows trips created or edited in the admin — not only those in code.
      const [trips, destinations] = await Promise.all([getTrips(), getDestinations()]).catch(() => [null, null]);
      const catalogue = trips && destinations ? { trips, destinations } : null;

      // Wrap each tool so running it both feeds the model and emits UI.
      const tools = conciergeTools.map((tool) => ({
        ...tool,
        run: async (input) => {
          const raw = await tool.run(input, catalogue);

          /**
           * `capture_interest` is the one tool with a server-side effect.
           *
           * Done here rather than in tools.js because this is where the
           * conversation id lives and where the record store is reachable —
           * tools.js stays data-shaped so it can be imported anywhere.
           *
           * A failure must never break the conversation. Losing a demand
           * signal is a shame; a chat that dies mid-sentence because a write
           * failed is the thing this feature was meant to prevent.
           */
          if (raw?._interest) {
            try {
              await recordInterest({
                conversationId,
                ...raw._interest,
                // The last few turns, so a salesperson can see how they asked
                // rather than only what the model distilled.
                transcript: body.messages
                  .slice(-6)
                  .map((m) => `${m.role === "user" ? "Them" : "Yaadi"}: ${m.content}`)
                  .join("\n")
                  .slice(0, 2000),
              });
            } catch (error) {
              console.error("[concierge] could not record interest", error);
            }
          }

          const { cards, forModel } = splitCards(raw);
          // Buffered rather than sent immediately: the cards should appear
          // under the sentence that introduces them, not before it.
          pendingCards.push(...cards);
          return forModel;
        },
      }));

      const note = pageContextNote(body.context);

      try {
        for await (const event of provider.streamWithTools({
          system: note ? `${CONCIERGE_SYSTEM}\n\n${note}` : CONCIERGE_SYSTEM,
          messages: body.messages,
          tools,
          maxOutputTokens: 4000,
          signal: request.signal,
        })) {
          if (event.type === "text") {
            send("text", { text: event.text });
          } else if (event.type === "tool") {
            send("tool", { name: event.name });
            // The tool has run, so whatever it produced can be shown now.
            if (pendingCards.length) {
              send("cards", { cards: pendingCards });
              pendingCards = [];
            }
          }
        }

        if (pendingCards.length) send("cards", { cards: pendingCards });
        send("done", {});
      } catch (error) {
        if (!request.signal.aborted) {
          const { message } = describeError(error);
          send("error", { message });
        }
      } finally {
        controller.close();
      }
    },
  });

  return new Response(stream, {
    headers: {
      "Content-Type": "text/event-stream; charset=utf-8",
      "Cache-Control": "no-cache, no-transform",
      Connection: "keep-alive",
      "X-Accel-Buffering": "no",
    },
  });
}
