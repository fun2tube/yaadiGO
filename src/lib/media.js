/** Fast lookup by id. */
const BY_ID = new Map(media.map((item) => [item.id, item]));

/**
 * Look up an image. Returns null rather than throwing, so a missing image
 * degrades to no image instead of a broken page — but <Img> warns loudly in
 * development so it gets noticed.
 */
export function getImage(id) {
  return BY_ID.get(id) ?? null;
}

/** Every image carrying a tag. */
export function imagesByTag(tag) {
  return media.filter((item) => item.tags.includes(tag));
}

/** Free-text search across title, alt, description and tags. */
export function searchImages(query) {
  const needle = query.trim().toLowerCase();
  if (!needle) return media;
  return media.filter((item) =>
    `${item.title} ${item.alt} ${item.description} ${item.tags.join(' ')}`
      .toLowerCase()
      .includes(needle)
  );
}

/** Every tag in use, with a count, for the gallery's filter rail. */
export function allTags() {
  const counts = new Map();
  for (const item of media) {
    for (const tag of item.tags) counts.set(tag, (counts.get(tag) ?? 0) + 1);
  }
  return [...counts.entries()]
    .map(([tag, count]) => ({ tag, count }))
    .sort((a, b) => b.count - a.count || a.tag.localeCompare(b.tag));
}

/** Attribution-required images, for the /credits page. */
export function attributionRequired() {
  return media.filter((item) => !/^(CC0|public domain)/i.test(item.credit.licence));
}
